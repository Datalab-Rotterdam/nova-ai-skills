// Writes embedded.js: every skill file and this package's version, so the installer also works
// where skills/ and package.json are not on disk (an app compiled into one executable, such as
// Nova AI Desktop's sidecar). Runs before packing; a test checks that the committed copy is current.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));

function listFiles(dir) {
    const files = [];
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
        const full = join(dir, entry.name);
        if (entry.isDirectory()) {
            if (entry.name !== '__pycache__') files.push(...listFiles(full));
        } else if (entry.isFile() && entry.name !== '.DS_Store') {
            files.push(full);
        }
    }
    return files;
}

/** The embedded.js source for the skills and package.json in `dir`. */
export function embeddedSource(dir = root) {
    const { version } = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    const files = {};
    for (const file of listFiles(join(dir, 'skills')).sort()) {
        const content = readFileSync(file);
        const text = content.toString('utf8');
        const name = relative(join(dir, 'skills'), file).split('\\').join('/');
        // Text stays readable in the diff; anything else is base64.
        files[name] = Buffer.from(text, 'utf8').equals(content) ? text : { base64: content.toString('base64') };
    }
    return `// Generated by scripts/embed.mjs - do not edit.\nexport const embedded = ${JSON.stringify({ version, files }, null, 1)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    writeFileSync(join(root, 'embedded.js'), embeddedSource());
}
